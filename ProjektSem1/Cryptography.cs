using System.Security.Cryptography;
using System.Text;

namespace ProjektSem1;

public class Cryptography
{
    //to regenerate keys create new instance of this object
    
    private readonly byte[] _rsaPublicKey;
    
    private readonly byte[] _rsaPrivateKey;

    private readonly byte[] _aesKey;
    
    public Cryptography()
    {
        _aesKey = GenerateRandomBytes(32);
        
        using var rsa = RSA.Create();

        rsa.KeySize = 8192;
        
        _rsaPublicKey = rsa.ExportRSAPublicKey();
            
        _rsaPrivateKey = rsa.ExportRSAPrivateKey();
    }
    
    
    
    //RSA
    
    /// <summary>
    /// get RSA public key
    /// </summary>
    /// <returns></returns>
    public byte[] GetPublicKey() => _rsaPublicKey;

    /// <summary>
    /// RSA encryption
    /// </summary>
    /// <param name="dataToEncrypt">data do encrypt [string]</param>
    /// <param name="publicKey">message destination server public key</param>
    /// <returns>encrypted data</returns>
    public byte[] RsaEncrypt(string dataToEncrypt, byte[] publicKey)
    {
        try
        {
            using var rsa = RSA.Create();
        
            rsa.ImportRSAPublicKey(publicKey, out _);
        
            return rsa.Encrypt(Encoding.UTF8.GetBytes(dataToEncrypt), RSAEncryptionPadding.OaepSHA256);
        }
        catch (Exception e)
        {
            Console.WriteLine($"Error in RSA encryption: {e.Message}", MessagesTypes.SysError);
        }
        
        return Array.Empty<byte>();
    }
    
    /// <summary>
    /// RSA encryption
    /// </summary>
    /// <param name="dataToEncrypt">data do encrypt [byte[]]</param>
    /// <param name="publicKey">message destination server public key</param>
    /// <returns>encrypted data</returns>
    public byte[] RsaEncrypt(byte[] dataToEncrypt, byte[] publicKey)
    {
        try
        {
            using var rsa = RSA.Create();
        
            rsa.ImportRSAPublicKey(publicKey, out _);
        
            return rsa.Encrypt(dataToEncrypt, RSAEncryptionPadding.OaepSHA256);
        }
        catch (Exception e)
        {
            Console.WriteLine($"Error in RSA encryption: {e.Message}", MessagesTypes.SysError);
        }
        
        return Array.Empty<byte>();
    }

    /// <summary>
    /// RSA decryption
    /// </summary>
    /// <param name="dataToDecrypt">data to decrypt</param>
    /// <returns>decrypted data</returns>
    public byte[] RsaDecrypt(byte[] dataToDecrypt)
    {
        try
        {
            using var rsa = RSA.Create();
        
            rsa.ImportRSAPrivateKey(_rsaPrivateKey, out _);
        
            return rsa.Decrypt(dataToDecrypt, RSAEncryptionPadding.OaepSHA256);
        }
        catch (Exception e)
        {
            Console.WriteLine($"Error in RSA decrypting: {e.Message}", MessagesTypes.SysError);
        }
        
        return Array.Empty<byte>();
    }

    
    
    //AES
    
    /// <summary>
    /// fill table with random generated bytes
    /// </summary>
    /// <param name="length">table lenght</param>
    /// <returns>byte table</returns>
    private byte[] GenerateRandomBytes(int length)
    {
        var randomBytes = new byte[length];
        
        using var rng = RandomNumberGenerator.Create();
        
        rng.GetBytes(randomBytes);
        
        return randomBytes;
    }
    
    /// <summary>
    /// AES-GCM encryption
    /// </summary>
    /// <param name="dataToEncrypt">data to encrypt [string]</param>
    /// <returns>secret key and message tables</returns>
    public (byte[] key, byte[] message) AesEncrypt(string dataToEncrypt)
    {
        try
        {
            var nonce = GenerateRandomBytes(12);
        
            var dataToEncryptBytes = Encoding.UTF8.GetBytes(dataToEncrypt);
        
            var encrypted = new byte[dataToEncryptBytes.Length];
        
            var tag = new byte[16];

            using var aes = new AesGcm(_aesKey, 16);
        
            aes.Encrypt(nonce, dataToEncryptBytes, encrypted, tag);
        
        
            var message = new byte[encrypted.Length + tag.Length];
        
            Array.Copy(tag, 0, message, 0,  tag.Length);
            Array.Copy(encrypted, 0, message, tag.Length, encrypted.Length);
        
        
            var secret = new byte[_aesKey.Length + nonce.Length];
        
            Array.Copy(_aesKey, 0, secret, 0, _aesKey.Length);
            Array.Copy(nonce, 0, secret, _aesKey.Length, nonce.Length);
        
            return (secret, message);
        }
        catch (Exception e)
        {
            Console.WriteLine($"Error in AES encryption: {e.Message}", MessagesTypes.SysError);
        }
        
        return (new byte[0], new byte[0]);
    }
    
    /// <summary>
    /// AES-GCM encryption
    /// </summary>
    /// <param name="dataToEncryptBytes">data to encrypt [byte[]]</param>
    /// <returns>secret key and message tables</returns>
    public (byte[] key, byte[] message) AesEncrypt(byte[] dataToEncryptBytes)
    {
        try
        {
            var nonce = GenerateRandomBytes(12);
        
            var encrypted = new byte[dataToEncryptBytes.Length];
        
            var tag = new byte[16];

            using var aes = new AesGcm(_aesKey, 16);
        
            aes.Encrypt(nonce, dataToEncryptBytes, encrypted, tag);
        
        
            var message = new byte[encrypted.Length + tag.Length];
        
            Array.Copy(tag, 0, message, 0,  tag.Length);
            Array.Copy(encrypted, 0, message, tag.Length, encrypted.Length);
        
        
            var secret = new byte[_aesKey.Length + nonce.Length];
        
            Array.Copy(_aesKey, 0, secret, 0, _aesKey.Length);
            Array.Copy(nonce, 0, secret, _aesKey.Length, nonce.Length);
        
            return (secret, message);
        }
        catch (Exception e)
        {
            Console.WriteLine($"Error in AES encryption: {e.Message}", MessagesTypes.SysError);
        }
        
        return (new byte[0], new byte[0]);
    }

    /// <summary>
    /// AES-GCM description
    /// </summary>
    /// <param name="secret">aes key + nonce</param>
    /// <param name="dataToDecrypt">tag + message</param>
    /// <returns></returns>
    public byte[] AesDecrypt(byte[] secret, byte[] dataToDecrypt)
    {
        try
        {
            var nonce = secret.TakeLast(12).ToArray();

            var key = secret.Take(32).ToArray();

            var tag = dataToDecrypt.Take(16).ToArray();

            var encrypted = dataToDecrypt.TakeLast(dataToDecrypt.Length - 16).ToArray();

            var plainText = new byte[encrypted.Length];

            using var aes = new AesGcm(key, 16);

            aes.Decrypt(nonce, encrypted, tag, plainText);

            return plainText;
        }
        catch (Exception e)
        {
            Console.WriteLine($"Error in AES decryption: {e.Message}", MessagesTypes.SysError);
        }
        
        return new byte[0];
    }
}